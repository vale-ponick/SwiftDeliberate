// MARK: - 🔗 СВЯЗЬ С ПАМЯТЬЮ (главное):

 /**   ┌────────────────┬────────────────────────────────────┐
   │ let / var      │ В стеке                          │
   │ Int, Bool      │ В стеке                          │
   │ String         │ В стеке (ссылка на кучу)        │
   │ Array          │ В стеке (ссылка на кучу)        │
   │ Dictionary     │ В стеке (ссылка на кучу)        │
   │ Optional       │ В стеке (контейнер)             │
   └────────────────┴────────────────────────────────────┘

  Почему let-структуру нельзя менять, а let-класс можно?
        1. Структура (struct) — Value Type (Семантика значений)
            Где живет: Сам объект целиком лежит в стеке (Stack). Переменная/константа — это и есть само значение.
        Что делает let: Замораживает весь регион памяти в стеке.
  
        Почему нельзя менять свойства?
        Изменение любого свойства (даже var) — это физическая перезапись байтов в стеке. Компилятор это блокирует.
        В методах структур для изменений нужен флаг mutating (передача self как inout), что для let запрещено.
  
        2. Класс (class) — Reference Type (Семантика указателей)
            Где живет: Сам объект (со свойствами, таблицей методов vtable и счетчиком ссылок RefCount) живет в куче (Heap). В стеке лежит только 64-битный указатель (адрес) на него.
        Что делает let: Замораживает только этот 64-битный указатель на стеке. Нельзя поменять адрес (присвоить другой объект или nil).
  
        Почему можно менять свойства?
        Изменение свойства класса — это разыменование указателя. Мы берем неизменяемый адрес на стеке, переходим по нему в кучу и пишем данные туда. На кучу ограничения let не распространяются — объект в куче даже «не знает», что на него ссылается константа.
  
  💡 Инженерный итог для собеседования:
        let для структуры гарантирует неизменяемость состояния (State Immutability), т.к. значение и есть переменная.
        let для класса гарантирует только неизменяемость ссылки (Reference Immutability), оставляя состояние объекта свободным для мутаций.
  */

/* 🎯 NOTA BENE:
 
 🔹 Всё, что в стеке — быстро + копируется + предсказуемо
 🔹 Всё, что в куче — медленнее -> ссылочное
 🔹 let = нельзя менять ссылку (адрес в стеке)
 🔹 var = можно менять ссылку (адрес в стеке)

 📎 См.: memoryLayers.swift (стек, куча, ссылки)
 📎 См.: errorsTypes.swift (типы ошибок)

 📸 ПРОСТАЯ СХЕМА ДЛЯ ЗАПОМИНАНИЯ

 ┌─────────────────────────────────────────────────────────────┐
 │                    СТРУКТУРА (struct)                       │
 │  ✅ Вся в стеке                                             │
 │  ✅ Копируется при передаче                                 │
 │  ✅ let = всё заморожено                                    │
 │  ✅ Используй по умолчанию                                  │
 └─────────────────────────────────────────────────────────────┘

 ┌─────────────────────────────────────────────────────────────┐
 │                    КЛАСС (class)                            │
 │  ✅ Ссылка в стеке → объект в куче                          │
 │  ✅ Передаётся по ссылке                                    │
 │  ✅ let = заморожена только ссылка                          │
 │  ✅ Используй, когда нужна идентичность или наследование    │
 └─────────────────────────────────────────────────────────────┘
 
 🎯 КОГДА ИСПОЛЬЗОВАТЬ
 struct                    class
 Данные не меняются        Нужно наследование
 Данные копируются         Нужна идентичность (ссылка)
 Лёгкие объекты            Работа с UIKit
 Модели данных (Codable)   Работа с файлами, сетью
 */
 
 /** 📌 КЛАССЫ vs СТРУКТУРЫ (для новичков)

 Ошибка: «Классы и структуры — это почти одно и то же»
 Правда: классы — ссылки (куча), структуры — значения (стек)

 Ошибка: «let запрещает всё менять»
 Правда: let для структуры — запрещает изменения, для класса — только смену ссылки

 Ошибка: «Нужно всегда использовать классы»
 Правда: В Swift по умолчанию — структуры

 Правило: структура = данные, класс = идентичность + поведение
 */
