/**
 🧠 A reference is not an object.
 It is a memory address pointing to the object's data (properties and methods).
 The reference lives in the stack, the object lives in the heap.


 📸 СХЕМА
 
 СТЕК                                КУЧА
 ┌─────────────────┐               ┌─────────────────┐
 │ let user = 0x1  │ ────────────▶ │ Объект User     │
 │                 │   адрес       │ name = "Alice"  │
 └─────────────────┘               └─────────────────┘

 1️⃣ ПЕРЕМЕННЫЕ И КОНСТАНТЫ (let / var)

   ┌──────────────┬────────────────────────────────────┐
   │ let          │ НЕЛЬЗЯ менять значение             │
   │ var          │ МОЖНО менять значение              │
   └──────────────┴────────────────────────────────────┘

   🔹 let — безопасность, читаемость, оптимизация
   🔹 var — только если значение реально меняется
*/

