import Foundation

// MARK: - 📌 БЛОК: BASICS (основы синтаксиса и памяти)

// ГЛАВНАЯ ИДЕЯ БЛОКА: ТИПЫ ДАННЫХ и их ПАМЯТЬ.

/**
 🧠 A reference is not an object.
 It is a memory address pointing to the object's data (properties and methods).
 The reference lives in the stack, the object lives in the heap.


 📸 СХЕМА
 
 СТЕК                                КУЧА
 ┌─────────────────┐               ┌─────────────────┐
 │ let user = 0x1  │ ────────────▶ │ Объект User     │
 │                 │   адрес       │ name = "Alice"  │
 └─────────────────┘               └─────────────────┘

 1️⃣ ПЕРЕМЕННЫЕ И КОНСТАНТЫ (let / var)

   ┌──────────────┬────────────────────────────────────┐
   │ let          │ НЕЛЬЗЯ менять значение             │
   │ var          │ МОЖНО менять значение              │
   └──────────────┴────────────────────────────────────┘

   🔹 let — безопасность, читаемость, оптимизация
   🔹 var — только если значение реально меняется
*/

// MARK: - 2️⃣ ТИПЫ ДАННЫХ (простые)
/**

   ┌──────────────┬────────────────────────────────────┐
   │ Int          │ Целые числа (64 бита)             │
   │ Double       │ Числа с плавающей точкой          │
   │ Bool         │ true / false                      │
   │ String       │ Текст                             │
   └──────────────┴────────────────────────────────────┘

   🔹 Все простые типы → лежат в СТЕКЕ (быстро)
*/

// MARK: - 3️⃣ КОЛЛЕКЦИИ (массивы, словари, множества)
/**
   ┌──────────────┬────────────────────────────────────┐
   │ Array        │ Упорядоченный список              │
   │ Dictionary   │ Ключ → значение                   │
   │ Set          │ Уникальные значения               │
   └──────────────┴────────────────────────────────────┘
*/
 /*
  🔹 Все коллекции → данные в КУЧЕ
  🔹 let → нельзя менять содержимое
  🔹 var → можно менять
  */


// MARK: - 4️⃣ ОПЦИОНАЛЫ (Optional)
/**
   ┌──────────────┬────────────────────────────────────┐
   │ T?           │ Есть значение (T) или nil         │
   │ !            │ Force unwrap (опасно!)            │
   │ if let       │ Безопасное извлечение             │
   │ guard let    │ Ранний выход                      │
   └──────────────┴────────────────────────────────────┘
 */
/*
 🔹 Опционал — это контейнер в памяти
 🔹 nil = отсутствие значения
 🔹 Всегда используй if let / guard let
*/

// MARK: - 5️⃣ УПРАВЛЕНИЕ ПОТОКОМ (Control Flow)
/**
   ┌──────────────┬────────────────────────────────────┐
   │ if-else      │ Ветвление                         │
   │ switch       │ Много вариантов                   │
   │ for-in      │ Перебор коллекции                 │
   │ while        │ Цикл с условием                   │
   │ repeat-while │ Цикл с пост-условием              │
   └──────────────┴────────────────────────────────────┘
 */
/*
 🔹 guard — ранний выход, обязательный return
 🔹 continue — пропустить итерацию
 🔹 break — выйти из цикла
 */

// MARK: - 🔗 СВЯЗЬ С ПАМЯТЬЮ (главное):

 /**   ┌────────────────┬────────────────────────────────────┐
   │ let / var      │ В стеке                          │
   │ Int, Bool      │ В стеке                          │
   │ String         │ В стеке (ссылка на кучу)        │
   │ Array          │ В стеке (ссылка на кучу)        │
   │ Dictionary     │ В стеке (ссылка на кучу)        │
   │ Optional       │ В стеке (контейнер)             │
   └────────────────┴────────────────────────────────────┘

  */

/* 🎯 NOTA BENE:
 
 🔹 Всё, что в стеке — быстро + копируется + предсказуемо
 🔹 Всё, что в куче — медленнее -> ссылочное
 🔹 let = нельзя менять ссылку (адрес в стеке)
 🔹 var = можно менять ссылку (адрес в стеке)
 */
