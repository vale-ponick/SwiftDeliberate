// MARK: - 📌 БЛОК: СТРУКТУРЫ, ВЫЧИСЛЯЕМЫЕ СВОЙСТВА И МОДИФИКАЦИЯ (Junior+ / Middle)

// ГЛАВНАЯ ИДЕЯ БЛОКА: Управление состоянием структур, оптимизация вычислений и совместимость версий Swift.

/**
 🧠 Value Types do not mutate implicitly.
 Изменение структуры изнутри её метода требует явного изменения self, что запрещено для констант (let).
 Вычисляемые свойства (Computed Properties) не хранят данные в памяти, а рассчитывают их "на лету".

 📸 СХЕМА РАБОТЫ METHOD MUTATION (Inout self)
 
 СТЕК
 ┌──────────────────────────┐
 │ var captainLog = Log()   │  ──▶ Можно вызвать mutating func (self передается как inout)
 ├──────────────────────────┤
 │ let kirkLog = Log()      │  ──▶ ОШИБКА КОМПИЛЯЦИИ: регион памяти заморожен, self изменить нельзя
 └──────────────────────────┘

 1️⃣ ВЫЧИСЛЯЕМЫЕ СВОЙСТВА (Computed Properties)

   ┌──────────────┬────────────────────────────────────────────────────────┐
   │ Stored       │ Хранит значение. Занимает физическое место в памяти.  │
   │ Computed     │ Не занимает память. Выполняет код при каждом вызове.  │
   └──────────────┴────────────────────────────────────────────────────────┘

   🔹 Используй computed properties вместо функций, если свойство читает/вычисляет состояние без аргументов.
   🔹 Осторожно: вычисление O(N) внутри свойства при частом вызове может замедлить приложение.
*/

// MARK: - 2️⃣ ОПТИМИЗАЦИЯ И СОВМЕСТИМОСТЬ ВЕРСИЙ (Swift 5 vs Swift 6)
/**
   Поиск и подсчет элементов в массиве можно делать разными способами. Разница — в памяти и версии языка.

   ┌───────────────────┬──────────────┬─────────────────────────────────────────────────────┐
   │ Метод             │ Сложность    │ Влияние на память и особенности                     │
   ├───────────────────┼──────────────┼─────────────────────────────────────────────────────┤
   │ .filter {}.count  │ O(N)         │ МЕДЛЕННО: Создает промежуточный массив в куче       │
   │ .count(where:)    │ O(N)         │ БЫСТРО: Без лишней памяти. Только в Swift 6.0+!     │
   │ .reduce(0) {}     │ O(N)         │ БЫСТРО: Без лишней памяти. Работает на Swift 5 и 6! │
   └───────────────────┴──────────────┴─────────────────────────────────────────────────────┘
*/

// MARK: - 3️⃣ КЛЮЧЕВОЕ СЛОВО MUTATING
/**
   В Swift структуры являются Value Types. По умолчанию их методы не могут изменять свойства.
   
   🔹 Флаг `mutating` говорит компилятору, что метод будет изменять (мутировать) свойства структуры.
   🔹 Под капотом: скрытый параметр `self` передается в этот метод как `inout` (по ссылке на область стека).
   🔹 Если объект структуры создан как `let`, вызвать `mutating` метод нельзя (компилятор заблокирует это).
 */

// MARK: - 4️⃣ БЕЗОПАСНОЕ УДАЛЕНИЕ И GUARD
/**
   При удалении элемента по критерию (например, по названию/Title):
   1. Сначала ищем индекс через `.firstIndex(where:)` -> возвращает опциональный `Int?`.
   2. Используем `guard let` вместо `if let`, чтобы избежать вложенности кода (пирамиды условий).
   3. Если индекс найден — удаляем через `.remove(at:)`, иначе — досрочно выходим через `return nil`.
 */

// MARK: - 5️⃣ ИТОГОВАЯ ШПАРГАЛКА-СХЕМА

/*
 ┌─────────────────────────────────────────────────────────────┐
 │                ВЫЧИСЛЯЕМЫЕ СВОЙСТВА (Computed)             │
 │  ✅ Вычисляются "на лету" при каждом обращении               │
 │  ✅ Если массив пуст, методы вроде .max() вернут nil        │
 │  ✅ Опциональный результат (Int?) требует ?? в принте       │
 │  ✅ Чистый результат (Int) избавляет от ?? в принте          │
 └─────────────────────────────────────────────────────────────┘

 ┌─────────────────────────────────────────────────────────────┐
 │                 МУТАЦИИ И ИЗМЕНЕНИЯ                         │
 │  ✅ func меняет структуру? -> Добавь `mutating`             │
 │  ✅ guard let -> уменьшает вложенность, чистит код          │
 │  ✅ Swift 6.0+ имеет .count(where:), но для iOS 15/16/17     │
 │     используй .reduce(0) для экономии памяти                │
 └─────────────────────────────────────────────────────────────┘
 
 🎯 ОШИБКА / ПРАВДА ДЛЯ СОБЕСЕДОВАНИЯ
 
 Ошибка: «.filter { $0.status == .high }.count — это нормальный способ подсчета»
 Правда: Это создаст копию отфильтрованного массива в памяти. Правильно использовать .reduce или .count(where:)
 
 Ошибка: «В вычисляемом свойстве всегда нужно проверять !entries.isEmpty перед .max()»
 Правда: Метод .max() сам по себе возвращает опционал (nil), если массив пуст. Проверка избыточна.
 
 Ошибка: «Если у структуры есть var-свойства, её методы могут менять их всегда»
 Правда: Только если перед функцией стоит ключевое слово `mutating` и сам объект создан как `var`.
 */
