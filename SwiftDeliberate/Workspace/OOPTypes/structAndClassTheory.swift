struct StructAndClassTheory {
    static func run() {
        print("▶️ Запуск: Struct And Class Theory")
        
        // MARK: - 🧠 МОЯ ФУНДАМЕНТАЛЬНАЯ РЕФЛЕКСИЯ
        
        /*
         1. Все, что не класс (class) — это структура (struct).
         2. Все базовые типы (Int, String, Array, Dictionary, Bool) — это structs.
         3. Присваивая их значение, мы КАЖДЫЙ РАЗ создаем КОПИЮ,
            а начальное свойство остается неизменным.
         */
        
        /**
         ИНЖЕНЕРНЫЙ ПЕРЕВОД:
         - Это называется Value Types (Типы значений).
         - Они копируются по значению при присваивании или передаче в функции.
         - Оригинал ВСЕГДА защищен от случайных изменений извне.
         */
        
        // MARK: - 📊 БОРТОВОЙ ЖУРНАЛ: ДИНАМИКА ОБУЧЕНИЯ (Ошибки vs Плюсы)
        
        /*
         
         | Категория                       | Статус / Анализ                                      | Вердикт (действуй, Vale!)       |
         | :---                            | :---                                                 | :---                                 |
         | ❌ Ошибка 1: Переключение       | В процессе лечения ⚠️. В задачах 1, 3, 4 контекст    | Dв Swift ВСЁ копируется.  |
         | контекста (Value/Refer)           | определен четко. Сбой был в блиц-тесте с билетами,   | Если видишь маркер 'class' — включай |
         |                                 | когда тип был скрыт. Мозг дефолтит в защиту (let).   | режим: «Один объект на двоих в Куче».|
         | ------------------------------- | ---------------------------------------------------- | ------------------------------------ |
         | ❌ Ошибка 2: Синтаксический     | Полностью УШЛА ✅. Класс SpaceProbe и его init        | Не гадаем за компилятор. Строгий     |
         | оптимизм                        | написаны руками с абсолютной точностью.              | синтаксис — залог компиляции.        |
         | ------------------------------- | ---------------------------------------------------- | ------------------------------------ |
         | ❌ Ошибка 3: Архитектурный      | Полностью УШЛА ✅. Код очищен от овержира. Ты сама   | Сниппет должен быть линейным и       |
