import Foundation

// 📌 ПАМЯТЬ В SWIFT: СТЕК, КУЧА, ССЫЛКИ

/**
 🧠 ДВА ГЛАВНЫХ СЛОЯ ПАМЯТИ

    ┌─────────────────────────────────────────────────────────┐
    │                     ПАМЯТЬ (ОЗУ)                       │
    └─────────────────────┬───────────────────────────────────┘
                          │
        ┌─────────────────┼─────────────────┐
        │                 │                 │
        ▼                 ▼                 ▼
┌───────────────────┐ ┌───────────────────┐ ┌───────────────────┐
│    СТЕК (Stack)   │ │   КУЧА (Heap)     │ │  ГЛОБАЛЬНАЯ       │
│                   │ │                   │ │  (Static/Global)  │
│ ✅ Быстрый        │ │ 🐢 Медленнее      │ │ 📦 Всё время жизни│
│ 📏 Фиксированный  │ │ 📐 Динамический   │ │                   │
│                   │ │                   │ │                   │
│ Хранит:           │ │ Хранит:           │ │ Хранит:           │
│ • адреса (ссылки) │ │ • объекты классов │ │ • константы       │
│ • структуры       │ │ • замыкания       │ │ • свойства типа   │
│ • Int, Bool       │ │ • большие строки  │ │                   │
│ • enum            │ │ • массивы (в куче)│ │                   │
└───────────────────┘ └───────────────────┘ └───────────────────┘


🏠 АНАЛОГИЯ:

   🔹 Стек     = icons in Dock Tile (быстро, мало)
   🔹 Куча     = apps: XCode, Pages, Safari (медленно, много) -> объекты классов, массивы
   🔹 Ссылка   = shortcat - ярлык


⚡️ КАК ЭТО ВЛИЯЕТ НА КОД

   ┌────────────────────────────┬────────────────────────────┐
   │ ДЕЙСТВИЕ                   │ ЧТО ПРОИСХОДИТ В ПАМЯТИ    │
   ├────────────────────────────┼────────────────────────────┤
   │ let x = 5                  │ Значение в СТЕКЕ           │
   │ var user = User(name: "A") │ Ссылка в СТЕКЕ             │
   │                            │ Объект в КУЧЕ              │
   │ user.name = "B"            │ Меняем объект в КУЧЕ       │
   │ user = User(name: "C")     │ Меняем ссылку в СТЕКЕ      │
   │                            │ (если user — var)          │
   └────────────────────────────┴────────────────────────────┘



🧠 NOTA BENE:

   📌 Структуры → в стеке (быстро, копируются)
   📌 Классы    → ссылка в стеке, объект в куче
   📌 let       → НЕЛЬЗЯ менять ссылку (адрес в стеке)
   📌 var       → МОЖНО менять ссылку (адрес в стеке)
 */
