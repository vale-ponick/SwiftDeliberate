import Foundation

struct ErrorsTypes {
    static func run() {
        print("▶️ Запуск: Errors Types")
        
        // 📌 ТИПЫ ОШИБОК В SWIFT (инженерный min)
        
        /**
         🔴 1. Ошибка компиляции (Compile‑time error)
         ────────────────────────────────────────
         ❌ Код НЕ собирается в программу
         ⏱️ Возникает ДО запуска
         ✅ Самая безопасная — нельзя пропустить
         📝 Пример: let a = 5; a = 10
         
         🟡 2. Логическая ошибка (Logic error)
         ──────────────────────────────────
         ✅ Код собирается и запускается
         ❌ Но выдаёт НЕПРАВИЛЬНЫЙ результат
         🕵️‍♀️ Трудно найти — не видна глазу
         📝 Пример: a + b вместо a * b
         
         🔥 3. Ошибка выполнения (Runtime error / Crash)
         ──────────────────────────────────────────────
         ✅ Код собирается и запускается
         💥 НО программа ПАДАЕТ во время работы
         🛡️ Защита: guard, if let, проверки
         📝 Examples:
         🔹 array[100] → выход за границы массива
         ⚠️ Force Unwrapping: `name!` при значении `nil` ➔ 💥 Crash
            напр.: `let name: String? = nil; print(name!)`
         Если опционал пуст, приложение рухнет «со звуком разбитого стекла» — главный виновник crashes in App Store.
         🔌 (Implicitly Unwrapped Optionals) — неявное извлечение.
            напр.: когда аутлеты интерфейса `@IBOutlet var label: UILabel!`
            еще не успели аллоцироваться в памяти, а код уже пытается к ним обратиться.
            Приложение падает мгновенно 💥.
         
         
         
         📊 СХЕМА (как это выглядит)
         
         ┌─────────────────────────────────────────────┐
         │                ОШИБКИ В ПРОГРАММЕ            │
         ├─────────────────────────────────────────────┤
         │                                             │
         │  ┌──────────────────┐                       │
         │  │ 🔴 Компиляции    │  ❌ не запускается   │
         │  └──────────────────┘                       │
         │                                             │
         │  ┌──────────────────┐                       │
         │  │ 🟡 Логическая    │  ✅ запускается     │
         │  │                  │  ❌ неверный ответ   │
         │  └──────────────────┘                       │
         │                                             │
         │  ┌──────────────────┐                       │
         │  │ 🔥 Runtime/crash │  ✅ запускается     │
         │  │                  │  💥 краш             │
         │  └──────────────────┘                       │
         │                                             │
         └─────────────────────────────────────────────┘
         
         
         
         📎 NOTA BENE:
         
         🔹 Ошибка компиляции → исправляешь ДО запуска
         🔹 Логическая → ищешь тестами и print
         🔹 Runtime → защищаешься через guard и if let
         */
    }
}
